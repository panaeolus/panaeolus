import { createHash } from "node:crypto";
import { appendCsoundSource, csoundString } from "./build";

export interface Analysis { text: string; partials: number; duration: number; top: number }
// Validate before passing a file to adsyn, including engines predating its
// bounds checks. Accept only HETRO's portable text format, never raw shorts.
export function parseHetro(source: string): Analysis {
  if (source.length > 262144) throw new Error("Analysis exceeds 256 KiB");
  const lines = source.trim().split(/\r?\n/).filter(line => line.trim());
  const header = /^HETRO (\d+)$/.exec(lines.shift() ?? "");
  const partials = Number(header?.[1]);
  if (!Number.isInteger(partials) || partials < 1 || partials > 64 || lines.length !== partials * 2)
    throw new Error("Expected HETRO text with 1–64 paired partial tracks");
  let duration = 0, top = 0;
  const tracks = lines.map((line, index) => {
    if (!/^-?[0-9]+(?:,-?[0-9]+)*$/.test(line)) throw new Error("Invalid HETRO track text");
    const values = line.split(",").map(Number);
    if (values.shift() !== (index % 2 === 0 ? -1 : -2) || values.pop() !== 32767 || values.length < 2 || values.length % 2)
      throw new Error("Expected paired amplitude/frequency breakpoints and terminator");
    let previous = -1;
    for (let i = 0; i < values.length; i += 2) {
      const time = values[i], value = values[i + 1];
      if (!Number.isInteger(time) || time <= previous || time > 30000 || (i === 0 && time !== 0) ||
          !Number.isInteger(value) || value < 0 || value > 32767)
        throw new Error("Breakpoints need increasing times from zero to 30000 ms and 16-bit values");
      previous = time;
    }
    if (index % 2 === 0 && values.at(-1) !== 0) throw new Error("Amplitude tracks must end at zero");
    return values;
  });
  const active: string[] = [];
  for (let i = 0; i < tracks.length; i += 2) {
    const amplitudes = tracks[i], frequencies = tracks[i + 1];
    // HETRO emits a single zero point for inaudible partials. Omit those
    // pairs rather than asking older adsyn loaders to walk empty tracks.
    if (!amplitudes.some((value, index) => index % 2 && value > 0)) continue;
    if (frequencies.length < 4 || frequencies.at(-2)! < amplitudes.at(-2)!)
      throw new Error("Frequency track must cover the amplitude track");
    duration = Math.max(duration, amplitudes.at(-2)! / 1000);
    for (let j = 1; j < frequencies.length; j += 2) top = Math.max(top, frequencies[j]);
    active.push(`-1,${amplitudes.join(",")},32767`, `-2,${frequencies.join(",")},32767`);
  }
  if (!active.length || !top || duration < 0.05) throw new Error("Analysis is silent or too short");
  return { text: `HETRO ${active.length / 2}\n${active.join("\n")}\n`, partials: active.length / 2, duration, top };
}

export function analysisPath(analysis: Analysis): string {
  return `panaeolus-hetro-${createHash("sha256").update(analysis.text).digest("hex")}.het`;
}

export function analysisModule(analysis: Analysis, name: string, root: number, trim: number): string {
  analysis = parseHetro(analysis.text);
  if (!/^[a-z][a-z0-9-]*$/.test(name) || ["nil", "true", "false"].includes(name))
    throw new Error("Use a lowercase instrument name with letters, digits, or hyphens, excluding nil, true, and false");
  if (!Number.isFinite(root) || root < 24 || root > 96 || !Number.isFinite(trim) || trim > 24)
    throw new Error("Invalid analysis root or gain");
  const path = analysisPath(analysis);
  const channel = `__${path}`;
  const embedded = Buffer.from(analysis.text).toString("base64");
  const chunks = (text: string, suffix: string) => {
    let forms = `(csound/eval ${JSON.stringify(`chnset "", "${channel}${suffix}"\nreturn 0`)})\n`;
    for (let offset = 0; offset < text.length; offset += 2048)
      forms += `(csound/eval ${JSON.stringify(appendCsoundSource(text.slice(offset, offset + 2048), channel + suffix))})\n`;
    return forms;
  };
  const install = `status:i = PanaeolusInstallAnalysis(${csoundString(path)}, chnget:S("${channel}"), chnget:S("${channel}_embedded"))\n` +
    `chnset "", "${channel}"\nchnset "", "${channel}_embedded"\nreturn status`;
  return `;; HETRO analysis: ${analysis.partials} partials, ${analysis.duration}s, root MIDI ${root}.\n` +
    `;; Generated by bun run hetro. Load before starting loops.\n` +
    chunks(analysis.text, "") + chunks(embedded, "_embedded") +
    `(when (< (csound/eval ${JSON.stringify(install)}) 0) (throw "Could not install HETRO analysis: cache full or conflicting content"))\n` +
    `(def ${name} (panaeolus.instruments.additive/analysis-voice ${JSON.stringify(path)} ${root} ${trim} ${analysis.duration} ${analysis.top}))\n`;
}
